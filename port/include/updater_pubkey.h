/**
 * updater_pubkey.h -- Embedded Ed25519 public key for the signed updater (SEC-6).
 *
 * This public key is the root of trust for auto-updates. Every release ZIP
 * downloaded by updater.c must carry a .sig sidecar that is a valid Ed25519
 * signature over the ZIP's SHA-256 digest concatenated with the tag string
 * (e.g. "v0.0.21"), signed by the matching private key. If the signature
 * does not verify, the update is rejected before any files are staged.
 *
 * Trust properties:
 *   - The public key does NOT rotate with the distribution channel (GitHub
 *     Releases). Compromising the GitHub account cannot forge a valid
 *     signature — only compromise of the private key can.
 *   - SHA-256 verification is independent (SEC-5). This binds the signature
 *     to the exact bytes of the ZIP.
 *   - The tag string is part of the signed message, so an attacker cannot
 *     re-use a signature from an older release on a different version tag.
 *
 * Key management:
 *   - DEVELOPMENT KEY: The constants below are a development key generated by
 *     devtools/keygen.ps1 (or keygen.sh). The matching private key lives in
 *     dev-keys/ed25519-private.pem and is gitignored.
 *   - PRODUCTION KEY: Before shipping a stable release to the general public,
 *     the developer MUST generate a separate production keypair offline and
 *     replace the constants below. The production private key MUST NEVER be
 *     checked into git, stored on a build server, or shared over any
 *     network — loss of that key permanently compromises the update channel.
 *
 * Regeneration:
 *   devtools/keygen.ps1       # Windows: writes updated public key into this file
 *   devtools/keygen.sh        # bash: same, for Linux/macOS dev machines
 */

